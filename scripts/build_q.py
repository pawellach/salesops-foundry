"""
build_q.py — Convert salesops-foundry SKILL.md files to Amazon Q Desktop compatible format.

Usage:
    python scripts/build_q.py [skills_dir] [output_dir]

Defaults:
    skills_dir  = skills/
    output_dir  = dist/q-skills/

Output files keep the same directory structure under output_dir.
Each file gets a comment header and trigger_phrases/tools/depends_on injected into frontmatter.
"""

import os
import re
import sys
import shutil

HEADER_COMMENT = "# Amazon Q Desktop compatible — generated by build_q.py\n"

# Words to strip when generating trigger phrases from name/description
_STOP_WORDS = {"a", "an", "the", "and", "or", "for", "with", "of", "in", "to", "on",
               "at", "by", "from", "is", "are", "as", "it", "its", "this", "that"}


def slugify_phrase(*tokens: str) -> str:
    return " ".join(t.lower() for t in tokens if t.lower() not in _STOP_WORDS)


def generate_trigger_phrases(name: str, description: str) -> list[str]:
    """Generate 3-5 trigger phrases from skill name and description."""
    name_words = [w.strip("()[].,") for w in name.split() if w.strip("()[].,")]
    desc_words = [w.strip("()[].,") for w in description.split() if w.strip("()[].,")]

    phrases = []

    # Phrase 1: full name lowercased
    phrases.append(name.lower())

    # Phrase 2: verb + key noun from name (first 2 content words)
    content_words = [w for w in name_words if w.lower() not in _STOP_WORDS]
    if len(content_words) >= 2:
        phrases.append(slugify_phrase(content_words[-1], content_words[0]))

    # Phrase 3: first verb from description + first noun from name
    desc_content = [w for w in desc_words if w.lower() not in _STOP_WORDS]
    if desc_content and content_words:
        verb_candidate = desc_content[0].lower().rstrip("s")
        phrases.append(f"{verb_candidate} {content_words[0].lower()}")

    # Phrase 4: "analyze/help with" + first noun
    if content_words:
        phrases.append(f"help with {content_words[0].lower()}")

    # Deduplicate preserving order
    seen = set()
    unique = []
    for p in phrases:
        if p not in seen:
            seen.add(p)
            unique.append(p)

    return unique[:5]


def parse_frontmatter(text: str) -> tuple[dict, str]:
    """Return (frontmatter_dict, body_after_closing_delimiter)."""
    if not text.startswith("---"):
        return {}, text

    end = text.find("\n---", 3)
    if end == -1:
        return {}, text

    fm_block = text[3:end].strip()
    body = text[end + 4:]  # skip '\n---'

    # Simple key: value parser (no nested YAML needed for our frontmatter)
    fm: dict = {}
    for line in fm_block.splitlines():
        if ":" in line:
            key, _, val = line.partition(":")
            fm[key.strip()] = val.strip().strip('"')
    return fm, body


def build_frontmatter(fm: dict) -> str:
    """Rebuild frontmatter YAML block, injecting Q fields if missing."""
    lines = []
    preserved_keys = ["name", "description", "group", "version", "status"]

    for key in preserved_keys:
        if key in fm:
            val = fm[key]
            # Quote values containing colons or special chars
            if any(c in val for c in [":", "#", "@", "'"]):
                lines.append(f'{key}: "{val}"')
            else:
                lines.append(f"{key}: {val}")

    # Inject Q-specific fields
    name = fm.get("name", "")
    description = fm.get("description", "")
    trigger_phrases = generate_trigger_phrases(name, description)

    lines.append("trigger_phrases:")
    for phrase in trigger_phrases:
        lines.append(f"  - \"{phrase}\"")

    lines.append("tools: []")
    lines.append("depends_on: []")

    return "---\n" + "\n".join(lines) + "\n---"


def process_skill(src_path: str, dst_path: str) -> None:
    with open(src_path, encoding="utf-8") as f:
        content = f.read()

    fm, body = parse_frontmatter(content)
    if not fm:
        # No frontmatter — copy as-is with header comment
        os.makedirs(os.path.dirname(dst_path), exist_ok=True)
        with open(dst_path, "w", encoding="utf-8") as f:
            f.write(HEADER_COMMENT + content)
        return

    new_fm = build_frontmatter(fm)
    output = HEADER_COMMENT + new_fm + body

    os.makedirs(os.path.dirname(dst_path), exist_ok=True)
    with open(dst_path, "w", encoding="utf-8") as f:
        f.write(output)


def main():
    script_dir = os.path.dirname(os.path.abspath(__file__))
    repo_root = os.path.dirname(script_dir)

    skills_dir = sys.argv[1] if len(sys.argv) > 1 else os.path.join(repo_root, "skills")
    output_dir = sys.argv[2] if len(sys.argv) > 2 else os.path.join(repo_root, "dist", "q-skills")

    if not os.path.isdir(skills_dir):
        print(f"ERROR: skills_dir not found: {skills_dir}")
        sys.exit(1)

    processed = 0
    for dirpath, _, filenames in os.walk(skills_dir):
        for filename in filenames:
            if filename != "SKILL.md":
                continue
            src = os.path.join(dirpath, filename)
            rel = os.path.relpath(src, skills_dir)
            dst = os.path.join(output_dir, rel)
            process_skill(src, dst)
            processed += 1

    print(f"build_q.py: processed {processed} skills -> {output_dir}")


if __name__ == "__main__":
    main()
